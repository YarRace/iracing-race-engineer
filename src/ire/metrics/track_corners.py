"""Повороты, найденные по форме трассы — чтобы на карте было за что зацепиться.

ЧЕСТНО О ГЛАВНОМ. Это НЕ официальная нумерация iRacing. Официальных
номеров взять негде: SDK их не отдаёт, а публичный набор контуров
(`iTelemetry/iracing-tracks`) — это один путь SVG без единой подписи.
Здесь повороты находятся по самой форме и нумеруются по ходу движения от
линии старт/финиш. На Сарте с её 38 «официальными» поворотами детектор
находит около четырнадцати: большинство остальных геометрически прямые, и
подписывать их номерами TV-графики значило бы врать.

ПОРОГ ПРОВЕРЕН ПО РУЛЮ, а не выбран на глаз. Считаем поворотом участок,
где курс сменился больше чем на MIN_TURN градусов. При 30° по четырём
официальным контурам выходит 12–15 поворотов. На тех же данных с другой
стороны: в его собственном круге по Ле-Ману (Porsche 963 GTP, 23822
кадра) участков, где руль держится выше 6° дольше двенадцати кадров, при
склейке ближе 0.4% круга — 14 при минимуме 15° поворота руля и 11 при
минимуме 40°. Два независимых способа дают одно и то же число.

Значит порог отбирает ровно те повороты, где человек реально крутит руль,
а не каждое отклонение линии.
"""
from __future__ import annotations

import math

# Смена курса, ниже которой это не поворот, а изгиб прямой.
MIN_TURN = 30.0

# Дрожание контура между соседними точками. Ресэмпл даёт 260 точек на круг,
# и на прямой соседние отрезки расходятся на доли градуса.
_STRAIGHT = 0.8


def _bearing(a, b):
    return math.atan2(b["y"] - a["y"], b["x"] - a["x"])


def _delta(h1, h2):
    """Разница курсов в градусах, приведённая к (-180, 180]."""
    return math.degrees(math.atan2(math.sin(h2 - h1), math.cos(h2 - h1)))


def find(points, min_turn=MIN_TURN):
    """Повороты по ходу движения: [{n, pct, x, y, angle, dir}].

    points — точки карты в порядке движения, как их хранит trackmap:
    x/y в 0..100 и pct — доля круга.

    Точка поворота — СЕРЕДИНА дуги, а не её начало: номер, поставленный на
    входе, читается как «поворот был раньше», и на карте это сбивает.
    """
    pts = [p for p in (points or [])
           if isinstance(p.get("x"), (int, float))
           and isinstance(p.get("y"), (int, float))]
    n = len(pts)
    if n < 8:
        return []

    # Ломаную НЕ замыкаем. Круг, конечно, замкнут, но у самодельной карты
    # между последней и первой точкой копится дрейф, и замыкающий отрезок —
    # это не поворот, а ошибка построения. Считать её поворотом значит
    # рисовать на старт/финише номер, которого там нет.
    head = [_bearing(pts[i], pts[i + 1]) for i in range(n - 1)]
    runs, acc, start, sign = [], 0.0, None, 0
    for i in range(len(head) - 1):
        d = _delta(head[i], head[i + 1])
        if abs(d) < _STRAIGHT:
            if start is not None and abs(acc) >= min_turn:
                runs.append((start, i, acc))
            acc, start, sign = 0.0, None, 0
            continue
        s = 1 if d > 0 else -1
        if sign and s != sign:
            # Курс развернулся в другую сторону — это уже следующий поворот,
            # а не продолжение прежнего. Иначе шикана слипается в один.
            if start is not None and abs(acc) >= min_turn:
                runs.append((start, i, acc))
            acc, start = 0.0, i
        if start is None:
            start = i
        sign = s
        acc += d
    if start is not None and abs(acc) >= min_turn:
        runs.append((start, len(head) - 1, acc))

    out = []
    for k, (a, b, ang) in enumerate(runs, 1):
        mid = pts[(a + b) // 2]
        out.append({"n": k,
                    "pct": mid.get("pct"),
                    "x": mid["x"], "y": mid["y"],
                    "angle": round(ang, 1),
                    "dir": "L" if ang > 0 else "R"})
    return out


def outward(points, corner, reach=6.0):
    """Куда отодвинуть подпись, чтобы она не легла на само полотно.

    Берём перпендикуляр к линии и пробуем обе стороны, выбирая ту, что
    ДАЛЬШЕ от всей ломаной. Проверять только направление «от центра
    фигуры» мало: у вогнутой трассы (а такая почти любая) центр лежит на
    полотне, и подпись садилась ровно в поворот — то есть туда, где по
    карте едут машины.
    """
    pts = points or []
    n = len(pts)
    if n < 3:
        return corner["x"], corner["y"]
    i = min(range(n), key=lambda k: (pts[k]["x"] - corner["x"]) ** 2
                                    + (pts[k]["y"] - corner["y"]) ** 2)
    a, b = pts[max(i - 1, 0)], pts[min(i + 1, n - 1)]
    dx, dy = b["x"] - a["x"], b["y"] - a["y"]
    ln = math.hypot(dx, dy) or 1.0
    nx, ny = -dy / ln, dx / ln

    def clearance(sx, sy):
        return min((p["x"] - sx) ** 2 + (p["y"] - sy) ** 2 for p in pts)

    plus = (corner["x"] + nx * reach, corner["y"] + ny * reach)
    minus = (corner["x"] - nx * reach, corner["y"] - ny * reach)
    return plus if clearance(*plus) >= clearance(*minus) else minus


def place(points, corners, reach=7.0, apart=9.0):
    """Подписи всех поворотов, разведённые так, чтобы не налезать друг на друга.

    Соседние повороты шиканы стоят в двух точках карты, и их номера
    садились один на другой — читалось как одно двузначное число. Тот,
    что не поместился, отодвигается дальше наружу, пока не разойдётся.
    """
    out = []
    for c in corners or []:
        r = reach
        for _ in range(6):
            x, y = outward(points, c, r)
            if all((x - px) ** 2 + (y - py) ** 2 >= apart ** 2 for px, py in out):
                break
            r += apart * 0.6
        out.append((x, y))
    return out


# Насколько далеко по кругу поворот с карты может стоять от апекса, чтобы
# считаться тем же поворотом. Полтора процента круга — это около 200 метров
# на Сарте и около 60 на Ватткинс-Глене; дальше это уже соседний поворот, и
# назвать его тем же номером значит показать пальцем не туда.
MATCH_PCT = 0.015


def match(apex_pcts, corners, tol=MATCH_PCT):
    """Номера поворотов КАРТЫ для сегментов разбора: [номер или None].

    ЗАЧЕМ. Поворотов у нас два разных счёта. Карта режет трассу по форме,
    разбор круга — по телеметрии (там, где машина реально гружена вбок).
    Числа не обязаны совпадать, и пока они расходятся, «теряешь 0.3 с в
    седьмом» показывает на карте не тот поворот. Человек поедет исправлять
    другое место.

    Здесь оба счёта связываются по доле круга. Не нашлось пары — None, и
    разбор честно покажет свой номер сегмента: соврать номером хуже, чем
    сказать «этот участок на карте не отмечен».
    """
    # Пары набираем ОТ САМОЙ БЛИЗКОЙ, и каждый номер уходит только одному
    # сегменту. Иначе два соседних сегмента получают один номер, а тот, что
    # между ними, — ничего: на экране два «поворота 7» и пропавший шестой.
    pairs = []
    for i, pct in enumerate(apex_pcts):
        if not isinstance(pct, (int, float)):
            continue
        for c in corners or []:
            cp = c.get("pct")
            if not isinstance(cp, (int, float)):
                continue
            # По кругу: 0.99 и 0.01 — соседи, а не противоположные концы.
            d = abs((pct - cp + 0.5) % 1.0 - 0.5)
            if d < tol:
                pairs.append((d, i, c.get("n")))

    out = [None] * len(apex_pcts)
    taken = set()
    for _, i, n in sorted(pairs):
        if out[i] is None and n not in taken:
            out[i] = n
            taken.add(n)
    return out
